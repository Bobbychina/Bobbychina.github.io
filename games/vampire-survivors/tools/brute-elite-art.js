/* ===========================================================
   两只"两关共用"的重型怪的模型重做（16×16）—— 由 gen-sprites.js 读取
   -----------------------------------------------------------
   【2026-09-25 站长点单】原来这两只太"可爱"了，要霸气、要恐怖：
   参考僵尸（腐烂、外露组织）与吸血鬼（苍白、嗜血）的元素，
   加上**骨头外露**与**绿色粘液**。
     brute 巨魔     —— 红色那只（config color #d1553f，第一关 200s 解锁，两关共用）
     elite 精英·血裔 —— 金色那只（config color #ffcc44，精英怪，两关共用）

   设计要点（16×16 很小，靠剪影和亮点立住）：
   巨魔 畸形壮汉：头缩在肩膀里、双肩高耸、驼背，肩/背顶出骨刺，
        胸腹被撕开 → 肋骨外露，嘴与臂下挂绿色粘液，眼睛是暗红亮点。
   精英 金甲尸将：破损金盔里露出骷髅头（黑洞眼眶 + 暗红瞳光）、
        肋骨外露、一手变成外露骨爪、披风破损、脚边淌粘液。
        金色骨架 + 苍白骨色对比，避免整只一片黄。

   两帧：0 = 站立，1 = 迈步（后腿抬起）。形状用代码构造，便于微调。
   =========================================================== */

'use strict';

const W = 16, H = 16;

/* ===========================================================
   1. 画布小工具
   =========================================================== */

function makeGrid() {
  const g = [];
  for (let y = 0; y < H; y++) g.push(new Array(W).fill('.'));
  return g;
}

/** 把网格变成行字符串；mirror=true 时左右镜像后再交给调用方（保证对称） */
function toRows(g) {
  return g.map((row) => row.join(''));
}

const P = {
  /** 单点 */
  px(g, x, y, ch) {
    if (x >= 0 && x < W && y >= 0 && y < H) g[y][x] = ch;
  },
  /** 水平线段 [x0, x1] 闭区间 */
  rect(g, x0, y0, x1, y1, ch) {
    for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) P.px(g, x, y, ch);
  },
  /** 从 x0 起写一行字符串，'.' 跳过 */
  stamp(g, x0, y, str) {
    for (let i = 0; i < str.length; i++) {
      if (str[i] === '.') continue;
      P.px(g, x0 + i, y, str[i]);
    }
  },
  /** 以 x=7.5 为中轴，把左侧画的内容镜像到右侧（画一半即可保证对称） */
  mirrorRight(g, centerX) {
    for (let y = 0; y < H; y++) {
      for (let x = 0; x < centerX; x++) {
        const ch = g[y][x];
        if (ch === '.') continue;
        const mx = centerX * 2 - 1 - x;
        if (mx >= 0 && mx < W) g[y][mx] = ch;
      }
    }
  }
};

/* ===========================================================
   2. 巨魔（红）—— 畸形壮汉，肋骨外露 + 肩背骨刺 + 绿色粘液
   =========================================================== */

const PAL_BRUTE = {
  '.': null,
  K: '#180b08',   // 轮廓（近黑）
  R: '#7d2418',   // 烂肉暗部
  r: '#a63a28',   // 烂肉中调
  o: '#c65638',   // 烂肉受光
  E: '#ff3b2f',   // 眼睛（暗红亮）
  B: '#b8ac8e',   // 骨头暗部
  b: '#e8dcc0',   // 骨头受光
  c: '#8e8468',   // 齿 / 骨缝
  G: '#4f8f2a',   // 粘液暗
  g: '#7cc23a',   // 粘液中
  l: '#a8e85c'    // 粘液高光
};

function drawBrute(frame) {
  const g = makeGrid();

  /* 双肩高耸 + 驼背：肩比头宽很多，头缩在中间（畸形感） */
  P.rect(g, 1, 4, 6, 4, 'K');           // 肩顶轮廓
  P.rect(g, 1, 5, 6, 6, 'r');
  P.rect(g, 2, 7, 6, 8, 'r');
  P.rect(g, 2, 5, 5, 5, 'o');           // 肩顶受光
  P.px(g, 1, 5, 'K'); P.px(g, 1, 6, 'K');
  /* 背上的骨刺（破体而出的骨） */
  P.px(g, 3, 3, 'K'); P.px(g, 3, 2, 'b'); P.px(g, 4, 3, 'c');
  P.px(g, 6, 3, 'K'); P.px(g, 6, 2, 'b');
  P.mirrorRight(g, 8);

  /* 头：小、缩进肩膀之间 */
  P.stamp(g, 5, 3, 'KKKKKK');
  P.stamp(g, 5, 4, 'KrEErK');           // 眼睛
  P.stamp(g, 5, 5, 'KRrrRK');
  P.stamp(g, 6, 6, 'KrrK');
  /* 獠牙 */
  P.px(g, 6, 6, 'b'); P.px(g, 9, 6, 'b');
  P.mirrorRight(g, 8);

  /* 躯干：胸口被撕开 → 肋骨外露 */
  P.rect(g, 4, 7, 11, 12, 'r');
  P.rect(g, 4, 7, 11, 7, 'o');
  P.rect(g, 3, 8, 3, 12, 'K');
  P.rect(g, 12, 8, 12, 12, 'K');
  P.rect(g, 6, 8, 9, 12, 'R');
  for (const y of [8, 10, 12]) {
    P.rect(g, 6, y, 9, y, 'B');
    P.rect(g, 7, y, 8, y, 'b');
    P.px(g, 6, y + 1, 'c');
  }
  P.mirrorRight(g, 8);

  /* 手臂：粗，垂在身侧 */
  P.rect(g, 1, 7, 3, 11, 'K');
  P.rect(g, 2, 8, 3, 11, 'R');
  P.rect(g, 2, 8, 2, 9, 'o');
  P.mirrorRight(g, 8);

  /* 绿色粘液：嘴下挂一缕、左臂下沿滴一滴 */
  P.px(g, 7, 7, 'G'); P.px(g, 8, 7, 'g');
  P.px(g, 8, 8, 'l');
  P.px(g, 2, 12, 'g'); P.px(g, 3, 12, 'G');
  P.px(g, 2, 13, 'l');

  /* 腿：13~14 行，10px 处收边 —— 不要落到最底行，否则显得腿过长 */
  P.rect(g, 4, 13, 6, 14, 'r');
  P.rect(g, 9, 13, 11, 14, 'r');
  P.rect(g, 4, 13, 6, 13, 'o');
  P.rect(g, 9, 13, 11, 13, 'o');
  P.rect(g, 3, 14, 6, 14, 'K');         // 脚
  P.rect(g, 9, 14, 12, 14, 'K');
  if (frame === 1) {
    /* 迈步：右腿抬起、左腿撑地 */
    P.rect(g, 9, 13, 12, 14, '.');
    P.rect(g, 12, 12, 13, 14, 'r');
    P.rect(g, 12, 14, 13, 14, 'K');
  }

  return toRows(g);
}

/* ===========================================================
   3. 精英·血裔（金）—— 破损金盔里的骷髅 + 外露骨爪 + 粘液
   =========================================================== */

const PAL_ELITE = {
  '.': null,
  K: '#191305',   // 轮廓
  G: '#7d6218',   // 金暗部
  g: '#c9a23c',   // 金中调
  Y: '#f2d478',   // 金受光
  W: '#a89c7c',   // 骨暗部
  w: '#ded4b4',   // 骨中调
  v: '#f2ecd8',   // 骨受光
  E: '#c8102e',   // 眼眶里的瞳光（吸血鬼那点红）
  S: '#4f8f2a',   // 粘液暗
  s: '#7cc23a',   // 粘液中
  l: '#a8e85c'    // 粘液高光
};

function drawElite(frame) {
  const g = makeGrid();

  /* --- 破损金盔：宽檐 + 盔顶尖，左檐崩掉一角（破败感） --- */
  P.rect(g, 2, 3, 13, 3, 'K');          // 檐的轮廓
  P.rect(g, 3, 2, 12, 2, 'g');          // 檐身
  P.rect(g, 2, 4, 13, 4, 'K');
  P.rect(g, 4, 1, 11, 1, 'g');          // 盔顶
  P.rect(g, 5, 1, 10, 1, 'Y');          // 盔顶受光
  P.rect(g, 2, 3, 3, 3, '.');           // 左檐崩口
  P.px(g, 2, 4, '.');
  P.px(g, 1, 3, 'G'); P.px(g, 1, 4, 'K');  // 崩口露出的暗金与断口

  /* --- 甲颚：金色面甲压住口鼻，只露出眼睛那条缝（像吸血鬼的护面） --- */
  P.rect(g, 3, 5, 12, 5, 'g');
  P.rect(g, 3, 5, 12, 5, 'g');
  P.px(g, 3, 5, 'K'); P.px(g, 12, 5, 'K');

  /* --- 眼缝：黑洞里两点红瞳（用 'r' 画眼眶，避免红糊成一片） --- */
  P.rect(g, 4, 6, 11, 6, 'K');
  P.px(g, 5, 6, 'E'); P.px(g, 6, 6, 'G');
  P.px(g, 9, 6, 'G'); P.px(g, 10, 6, 'E');

  /* --- 下半张脸：外露的下颌骨 + 齿列（加深轮廓，别糊成一片白） --- */
  P.rect(g, 4, 7, 11, 9, 'K');
  P.rect(g, 5, 7, 10, 8, 'w');
  P.rect(g, 5, 7, 10, 7, 'v');
  P.rect(g, 5, 9, 10, 9, 'W');
  for (let x = 5; x <= 10; x += 2) P.px(g, x, 8, 'K');   // 齿缝：用轮廓色，才看得出牙
  for (let x = 5; x <= 10; x += 2) P.px(g, x, 9, 'W');

  /* --- 躯干：金胸甲，腹部被撕开 → 肋骨外露 --- */
  P.rect(g, 3, 10, 12, 13, 'g');
  P.rect(g, 3, 10, 12, 10, 'Y');
  P.rect(g, 3, 10, 3, 13, 'K');
  P.rect(g, 12, 10, 12, 13, 'K');
  P.rect(g, 6, 11, 9, 13, 'G');         // 破口暗底
  for (const y of [11, 12]) {
    P.rect(g, 6, y, 9, y, 'w');
    P.rect(g, 7, y, 8, y, 'v');
  }
  /* 肩甲：两片金护肩，与躯干连成一体（不留缝） */
  P.rect(g, 2, 10, 4, 11, 'g');
  P.px(g, 2, 10, 'Y'); P.px(g, 2, 11, 'K');
  P.rect(g, 11, 10, 13, 11, 'g');
  P.px(g, 13, 10, 'Y'); P.px(g, 13, 11, 'K');

  /* --- 双臂：都从肩甲下沿接下来，长度到第 13 行，和躯干相接 --- */
  P.rect(g, 2, 12, 3, 13, 'g');         // 左臂（金甲）
  P.px(g, 2, 12, 'Y');
  P.rect(g, 12, 12, 13, 13, 'w');       // 右臂（外露骨爪）
  P.rect(g, 12, 12, 13, 12, 'v');
  P.px(g, 3, 13, 'G'); P.px(g, 12, 13, 'W');

  /* --- 绿色粘液：从肋骨的破口往下淌，脚边一滩 --- */
  P.px(g, 7, 14, 's'); P.px(g, 8, 14, 'S');
  P.px(g, 8, 15, 'l');

  /* --- 腿：13~14 行。迈步时整条右腿挪到 12~13 列，宽度与站立一致 --- */
  P.rect(g, 4, 13, 6, 14, 'g');
  P.rect(g, 4, 13, 6, 13, 'Y');
  P.rect(g, 3, 14, 6, 14, 'K');
  if (frame === 0) {
    P.rect(g, 9, 13, 11, 14, 'g');
    P.rect(g, 9, 13, 11, 13, 'Y');
    P.rect(g, 9, 14, 12, 14, 'K');
  } else {
    /* 抬腿：右腿前移一格半，仍是 3 格宽 + 4 格靴 */
    P.rect(g, 12, 12, 14, 13, 'g');
    P.rect(g, 12, 12, 14, 12, 'Y');
    P.rect(g, 12, 13, 15, 13, 'K');
  }

  return toRows(g);
}

